CREATE TABLE food_items (
    food_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    food_name VARCHAR2(100) NOT NULL,
    price NUMBER(10,2) NOT NULL CHECK (price >= 0),
    category VARCHAR2(50),
    is_available CHAR(1) DEFAULT 'Y'
        CHECK (is_available IN ('Y', 'N'))
);

CREATE TABLE food_orders (
    order_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_name VARCHAR2(100) NOT NULL,
    phone VARCHAR2(20) NOT NULL,
    delivery_address VARCHAR2(500) NOT NULL,
    order_total NUMBER(10,2) DEFAULT 0 NOT NULL,
    order_status VARCHAR2(20) DEFAULT 'PLACED' NOT NULL,
    order_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE order_items (
    order_item_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id NUMBER NOT NULL,
    food_id NUMBER NOT NULL,
    quantity NUMBER(5) NOT NULL CHECK (quantity > 0),
    unit_price NUMBER(10,2) NOT NULL CHECK (unit_price >= 0),
    subtotal NUMBER(10,2) NOT NULL CHECK (subtotal >= 0),

    CONSTRAINT fk_order_items_order
        FOREIGN KEY (order_id)
        REFERENCES food_orders(order_id),

    CONSTRAINT fk_order_items_food
        FOREIGN KEY (food_id)
        REFERENCES food_items(food_id)
);

